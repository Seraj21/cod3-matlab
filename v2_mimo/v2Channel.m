function channel=v2Channel(cfg,front,sampleRate,seed)
% HARQ can retain one fading realization while advancing its physical time.
initialTime=0;
if isfield(cfg,'ChannelSeed'),seed=cfg.ChannelSeed;end
if isfield(cfg,'ChannelInitialTime'),initialTime=cfg.ChannelInitialTime;end
receive=kron(eye(cfg.Users),toeplitz(cfg.UECorrelation.^(0:cfg.UERx-1)));
channel=nrTDLChannel('DelayProfile','TDL-C','DelaySpread',cfg.DelaySpread, ...
 'MaximumDopplerShift',cfg.Speed/3.6*cfg.CarrierFrequency/299792458, ...
 'SampleRate',sampleRate,'PathGainSampleRate','auto', ...
 'MIMOCorrelation','Custom','Polarization','Co-Polar', ...
 'TransmitCorrelationMatrix',front.Correlation,'ReceiveCorrelationMatrix',receive, ...
 'NormalizePathGains',true,'NormalizeChannelOutputs',false, ...
 'RandomStream','mt19937ar with seed','Seed',seed,'InitialTime',initialTime, ...
 'ChannelResponseOutput','ofdm-response');
end
