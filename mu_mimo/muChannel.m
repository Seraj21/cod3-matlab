function channel = muChannel(cfg,front,sampleRate,seed)
ue = toeplitz(cfg.UECorrelation.^(0:cfg.UERx-1));
receive = kron(eye(cfg.Users),ue);
channel = nrTDLChannel('DelayProfile','TDL-C','DelaySpread',cfg.DelaySpread, ...
    'MaximumDopplerShift',cfg.Speed/3.6*cfg.CarrierFrequency/299792458, ...
    'SampleRate',sampleRate,'PathGainSampleRate','auto', ...
    'NumTransmitAntennas',cfg.RFChains,'NumReceiveAntennas',cfg.Users*cfg.UERx, ...
    'MIMOCorrelation','Custom','Polarization','Co-Polar', ...
    'TransmitCorrelationMatrix',front.Correlation,'ReceiveCorrelationMatrix',receive, ...
    'NormalizePathGains',true,'NormalizeChannelOutputs',false, ...
    'RandomStream','mt19937ar with seed','Seed',seed, ...
    'ChannelResponseOutput','ofdm-response');
end
